"""번호·기한·판정 규칙. 업무설명(data/업무설명_하자보수.md) 4~5항을 그대로 코드로 옮긴 파일.
AI를 부르지 않는다. 같은 입력이면 항상 같은 결과가 나온다."""
import csv
from datetime import date, timedelta
from pathlib import Path

BASE = Path(__file__).parent
공사정보_경로 = BASE / "data" / "공사정보.csv"

만료임박_일수 = 30
조치기한_일수 = {"긴급": 1, "높음": 3, "보통": 7}


def _날짜(값) -> date:
    """date 또는 'YYYY-MM-DD' 글자를 date로."""
    return 값 if isinstance(값, date) else date.fromisoformat(str(값))


def 공사정보_읽기(경로=공사정보_경로) -> list[dict]:
    with open(경로, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def 접수번호(접수일, 순번: int) -> str:
    """HJ-접수일(YYYYMMDD)-순번(01부터). 순번은 같은 접수일 안에서 센다."""
    return f"HJ-{_날짜(접수일):%Y%m%d}-{순번:02d}"


def 긴급도(긴급근거: dict) -> str:
    """긴급: 누수, 전기 이상, 고객 안전 위험 / 높음: 고객 출입·영업 지장, 고객 민원 / 보통: 그 외."""
    if 긴급근거.get("누수") or 긴급근거.get("전기이상") or 긴급근거.get("안전위험"):
        return "긴급"
    if 긴급근거.get("출입영업지장") or 긴급근거.get("고객민원"):
        return "높음"
    return "보통"


def 조치기한(접수일, 긴급도값: str) -> date:
    """접수일 + 1일(긴급) / 3일(높음) / 7일(보통)."""
    return _날짜(접수일) + timedelta(days=조치기한_일수[긴급도값])


def 보증만료일(준공일, 보증기간_년) -> date:
    """준공일 + 하자보증기간(년). 2월 29일 준공은 해당 연도에 29일이 없으면 2월 28일로 둔다."""
    준공 = _날짜(준공일)
    연도 = 준공.year + int(보증기간_년)
    try:
        return 준공.replace(year=연도)
    except ValueError:
        return 준공.replace(year=연도, day=28)


def _공종_후보(공종: str) -> list[str] | None:
    """'설비/타일' -> ['설비','타일']. 공종 미정('확인필요', 빈 값)이면 None."""
    if not 공종 or 공종.strip() == "확인필요":
        return None
    return [c.strip() for c in 공종.split("/") if c.strip()]


def _만료임박(접수: date, 만료: date) -> bool:
    """접수일 기준으로 보증내이고 만료일까지 30일 이내."""
    return 접수 <= 만료 and (만료 - 접수).days <= 만료임박_일수


def 보증판정(접수일, 위치: str, 공종: str, 공사목록: list[dict]) -> dict:
    """위치와 공종이 모두 같은 공사를 찾아 보증 관련 칸을 돌려준다. 기준은 오늘이 아니라 접수일.

    - 공사 1건 + 접수일 <= 보증만료일(같은 날 포함) -> 보증내 / 시공업체
    - 공사 1건 + 접수일 > 보증만료일               -> 보증만료 / 자체보수
    - 공종 미정·후보 2개 이상, 공사 없음, 공사 2건 이상 -> 확인필요 (책임구분 비움)
    - 보증내이고 만료일까지 30일 이내면 비고에 만료임박.
      확인필요 건도 후보 공사가 만료임박이면 비고에 후보 공사번호와 함께 적는다.
    """
    접수 = _날짜(접수일)
    후보공종 = _공종_후보(공종)
    같은위치 = [c for c in 공사목록 if c["위치"] == 위치]

    # 공종이 하나로 정해졌을 때만 위치+공종 완전 일치 조회
    일치 = []
    if 후보공종 and len(후보공종) == 1:
        일치 = [c for c in 같은위치 if c["공종"] == 후보공종[0]]

    if len(일치) == 1:
        공사 = 일치[0]
        만료 = 보증만료일(공사["준공일"], 공사["하자보증기간(년)"])
        내 = 접수 <= 만료
        return {
            "공사번호": 공사["공사번호"],
            "시공업체": 공사["시공업체"],
            "준공일": 공사["준공일"],
            "보증만료일": 만료.isoformat(),
            "보증판정": "보증내" if 내 else "보증만료",
            "책임구분": "시공업체" if 내 else "자체보수",
            "비고": "만료임박" if 내 and _만료임박(접수, 만료) else "",
        }

    # 확인필요: 후보 공사 = 같은 위치이면서 후보 공종(공종 미정이면 전부)에 해당하는 공사
    후보공사 = [c for c in 같은위치 if 후보공종 is None or c["공종"] in 후보공종]
    임박 = []
    for 공사 in 후보공사:
        만료 = 보증만료일(공사["준공일"], 공사["하자보증기간(년)"])
        if _만료임박(접수, 만료):
            임박.append(f'{공사["공사번호"]}(보증만료 {만료.isoformat()})')
    return {
        "공사번호": "",
        "시공업체": "",
        "준공일": "",
        "보증만료일": "",
        "보증판정": "확인필요",
        "책임구분": "",
        "비고": "만료임박 후보: " + ", ".join(임박) if 임박 else "",
    }
